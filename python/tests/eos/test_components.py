"""The component databank: does a name give the substance it says it does.

The file it reads is generated by `tools/gen_databank.py` from NeqSim, and the one
thing that can go wrong with a generator like that is not a crash - it is a
conversion applied uniformly and wrongly, producing 173 rows that all agree with
each other and none of which are right. A factor of 1000 in molar mass, 273.15 in
temperature, or 1e5 in pressure would look entirely reasonable in every row.

So the tests below do not compare the databank against itself. They compare it
against values known independently of NeqSim - methane's critical point is a
published constant - and against the arithmetic the rest of the library already
does on the same numbers.
"""

from __future__ import annotations

import pytest

from azoth.core.errors import InvalidInputError, PropertyUnavailableError
from azoth.eos import Component, available_components, component, from_names
from azoth.eos import components as databank


def test_the_databank_is_populated() -> None:
    """A file that parsed to nothing would make every other test here vacuous."""
    assert len(available_components()) > 100, (
        f"the databank has {len(available_components())} substances; it should have "
        f"roughly 173. Regenerate with tools/gen_databank.py."
    )


@pytest.mark.parametrize(
    ("name", "tc_k", "pc_pa", "omega"),
    [
        # Published critical constants, not NeqSim outputs. If a conversion in the
        # generator is wrong by a factor, these are what say so.
        ("methane", 190.564, 4.5992e6, 0.0115),
        ("ethane", 305.32, 4.872e6, 0.0995),
        ("propane", 369.83, 4.248e6, 0.1523),
        ("n-butane", 425.12, 3.796e6, 0.2002),
        # Water is the one entry that does not agree to the file's precision, and it
        # is the data rather than the conversion: NeqSim carries `220.89` bar where
        # IAPWS gives `220.64`, which is 0.11% high. The tolerance below is widened
        # for it rather than the value being written down as if it were right - the
        # conversion is exact (`220.89 bar` is `22089000.0 Pa` to the digit), so what
        # this records is the accuracy of the source, which is the thing a caller
        # relying on this databank should know.
        ("water", 647.096, 2.2064e7, 0.3443),
    ],
)
def test_a_named_substance_is_the_substance(
    name: str, tc_k: float, pc_pa: float, omega: float
) -> None:
    """The databank's values against the literature, within the file's precision."""
    entry = databank.entry(name)
    tolerance = 2e-3 if name == "water" else 1e-3

    assert entry.Tc.to("K").magnitude == pytest.approx(tc_k, rel=tolerance), f"{name}: Tc"
    assert entry.Pc.to("Pa").magnitude == pytest.approx(pc_pa, rel=tolerance), f"{name}: Pc"
    assert entry.omega == pytest.approx(omega, abs=1e-3), f"{name}: omega"


def test_molar_mass_is_in_kg_per_mol_and_not_g_per_mol() -> None:
    """The conversion that would be invisible: every row a factor of 1000 out.

    NeqSim's file stores g/mol and its loader divides by 1000. A generator that
    dropped that step would produce a databank of numbers that are all exactly
    1000x too large, agree with each other, and produce densities three orders of
    magnitude wrong.
    """
    methane = databank.entry("methane")
    # `molar_mass` is optional because a component a keycard *adds* has none - a
    # keycard supplies the parameters a cubic reads and nothing else. A substance in
    # the shipped databank always has one, which is what this asserts.
    assert methane.molar_mass is not None
    assert methane.molar_mass.to("kg/mol").magnitude == pytest.approx(0.016043, rel=1e-4)
    # The sanity check that catches it without knowing the answer: a mol of methane
    # weighs about 16 grams, and 16 kg/mol is not a substance.
    assert 0.001 < methane.molar_mass.to("kg/mol").magnitude < 1.0


def test_temperature_is_kelvin_and_not_celsius() -> None:
    """Methane boils at 111 K and its critical point is 190 K. In Celsius it is
    -82 C, which is also a plausible number for a temperature column."""
    assert databank.entry("methane").Tc.to("K").magnitude > 100.0


def test_an_unknown_name_is_refused_rather_than_substituted() -> None:
    """An error, not a default: a near neighbour's constants give a plausible answer
    for the wrong substance."""
    with pytest.raises(PropertyUnavailableError) as excinfo:
        component("unobtainium")
    assert "unobtainium" in str(excinfo.value)
    assert "173" in str(excinfo.value), "the message should say how many there are"


def test_a_name_is_matched_case_insensitively() -> None:
    assert component("Methane").Tc == component("methane").Tc


def test_from_names_builds_the_mixture_a_caller_would_have_built_by_hand() -> None:
    """The convenience is a lookup, not a second way of building a mixture.

    Whatever `from_names` returns must be what the caller gets by writing the
    critical constants out, because that is what every spec case does and what the
    two implementations are checked against.
    """
    by_name = from_names(["methane", "n-butane"])
    by_hand = [
        Component(
            Tc=databank.entry("methane").Tc,
            Pc=databank.entry("methane").Pc,
            omega=databank.entry("methane").omega,
        ),
        Component(
            Tc=databank.entry("n-butane").Tc,
            Pc=databank.entry("n-butane").Pc,
            omega=databank.entry("n-butane").omega,
        ),
    ]

    assert len(by_name) == 2
    for from_lookup, written_out in zip(by_name.components, by_hand, strict=True):
        assert from_lookup.Tc == written_out.Tc
        assert from_lookup.Pc == written_out.Pc
        assert from_lookup.omega == written_out.omega


def test_from_names_takes_the_published_interaction_parameters() -> None:
    """The difference between `from_names` and a hand-built mixture: the `kij`.

    A caller writing `Component(...)` twice gets zeros, which is the ideal-mixture
    assumption. `from_names` gets the fitted value the databank has, and the two
    are not the same answer.
    """
    mixture = from_names(["water", "methane"])
    assert mixture.kij[0][1] == pytest.approx(0.651, abs=1e-6), (
        "water/methane is a strongly non-ideal pair; a zero here would mean the "
        "interaction table was not read"
    )
    assert mixture.kij[0][0] == 0.0, "the diagonal must stay zero"


def test_a_pair_the_databank_does_not_have_is_zero() -> None:
    """An unlisted pair falls back to the ideal-mixture assumption, which is what
    `mixture()` does with an omitted pair rather than something new."""
    mixture = from_names(["methane", "ethane", "propane"])
    # Whatever the databank holds, the matrix must be symmetric and zero-diagonal.
    for i in range(3):
        assert mixture.kij[i][i] == 0.0
        for j in range(3):
            assert mixture.kij[i][j] == mixture.kij[j][i]


def test_from_names_reports_a_name_it_does_not_have() -> None:
    with pytest.raises(PropertyUnavailableError):
        from_names(["methane", "unobtainium"])


def test_mixture_of_returns_the_polynomial_beside_the_mixture() -> None:
    """The one path a calculation takes to its data.

    A mixture without heat-capacity coefficients cannot produce an enthalpy, so the
    two come back together - and the coefficients come from the same file the
    constants do, which is what stops a spec file carrying them.
    """
    fluid, ideal_gas = databank.mixture_of(["methane", "n-butane"])

    assert len(fluid) == 2
    assert len(ideal_gas.cp_a) == 2
    assert len(ideal_gas.cp_e) == 2

    # Methane's constant term, as NeqSim's COMP.csv has it. Retyped here on purpose: a
    # test that read the same table it is testing would agree with any table at all.
    assert ideal_gas.cp_a[0] == pytest.approx(37.978_352)
    assert fluid.kij[0][1] == pytest.approx(0.01289789)


def test_mixture_of_takes_the_same_components_from_names_alone() -> None:
    """The constants are the ones `component()` gives, so nothing is restated."""
    fluid, _ = databank.mixture_of(["methane", "n-butane"])
    by_name = from_names(["methane", "n-butane"])

    assert fluid.components[0].Tc == by_name.components[0].Tc
    assert fluid.components[1].omega == by_name.components[1].omega
    assert fluid.kij[0][1] == by_name.kij[0][1]


def test_mixture_of_refuses_an_empty_list() -> None:
    with pytest.raises(InvalidInputError):
        databank.mixture_of([])


def test_every_shipped_substance_has_heat_capacity_coefficients() -> None:
    """The databank's own completeness, which a spec cannot assert.

    A substance with constants but no polynomial is one a cubic can flash and nothing
    can give an enthalpy for - the failure would surface as an outage a long way from
    the row that caused it.
    """
    missing = [name for name in available_components() if databank.entry(name).cp is None]
    assert not missing, f"no heat-capacity coefficients for {missing}"


def test_the_reference_state_column_is_carried_and_never_blank() -> None:
    """`REFERENCESTATETYPE` decides which branch `ComponentGE.fugcoef` takes.

    It was recorded in the ledger as `empty-upstream` and dropped. It is not empty: over
    exactly the 173 rows the databank keeps, NeqSim's `COMP.csv` fills it on every one -
    `solvent` on 122, `solute` on 49, and the literal `0.0` on the two acids. A column
    that is read to *choose an arithmetic* cannot be absent, and a blank here would have
    to mean something.
    """
    blank = [name for name in available_components() if not databank.entry(name).reference_state]
    assert not blank, f"no reference state for {blank}"

    assert databank.entry("methanol").reference_state == databank.SOLVENT
    assert databank.entry("CO2").reference_state == "solute"


def test_the_activity_phase_refuses_a_henrys_law_component() -> None:
    """The Henry branch is a different arithmetic and is not ported.

    `ComponentGE.fugcoef` returns `gamma_i P0_i / P` for a `solvent` component and a
    Henry's-law coefficient for any other tag. Computing the first for a component the
    database tags the second way would be a wrong number with no symptom, so the phase's
    parameter resolver refuses rather than approximates.
    """
    assert databank.ge_nrtl_phase_parameters(["methanol", "water"]).antoine_type

    for name in ("CO2", "methane", "n-hexane", "nitric acid"):
        with pytest.raises(InvalidInputError) as raised:
            databank.ge_nrtl_phase_parameters([name, "water"])
        assert name.lower() in str(raised.value)


def test_uniquac_r_and_q_are_the_group_sums_neqsim_computes() -> None:
    """The one half of UNIQUAC that has a differential oracle.

    `eos.uniquac_activity_coefficients` resolves `r` and `q` from the UNIFAC group
    sums, and NeqSim's `ComponentGEUnifac.getR`/`getQ` compute the same sums from the
    same table. Measured through `validation/neqsim/GeUniquacPhi.java`, they agree to
    the last bit rather than to a tolerance, which is what reading one table through
    one arithmetic should give.

    The composition has no oracle - `ComponentGEUniquac.getGamma` returns 0.0 and its
    formula is commented out - so this is the only part of the model NeqSim can
    confirm. `rUNIQUAQ`/`qUNIQUAQ`, the different pair NeqSim's own constructor reads,
    are 0.0 for 109 of the table's 112 rows and are not the source here.
    """
    names = ["methanol", "water", "nc10", "benzene", "n-hexane"]
    measured = {
        "methanol": (1.4311, 1.432),
        "water": (0.92, 1.4),
        "nc10": (7.1974, 6.016),
        "benzene": (3.1878, 2.4000000000000004),
        "n-hexane": (4.4998000000000005, 3.856),
    }
    params = databank.uniquac_parameters(names)

    for i, name in enumerate(names):
        want_r, want_q = measured[name]
        assert params.r[i] == want_r, f"{name}: r is {params.r[i]!r}, NeqSim says {want_r!r}"
        assert params.q[i] == want_q, f"{name}: q is {params.q[i]!r}, NeqSim says {want_q!r}"
