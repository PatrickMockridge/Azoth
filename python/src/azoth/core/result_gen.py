"""The result dataclasses, emitted from the extension's own declarations.

Generated by `tools/gen_python_result.py` - see its module documentation for the three
declarations each one is a function of. **Do not edit by hand.** Several notes that used
to sit on one class and are true of all of them:

* **why `eq=False`.** `__eq__` would compare `pint` quantities, whose equality is not
  what a numerical test wants; results are compared within a tolerance, by
  :func:`azoth.testing.assert_results_equal`, which makes the tolerance visible.
* **why warnings are tuples.** Immutable, and they match `Vec<Warning>`; a result whose
  caveats can be edited after the fact is a result whose caveats can be removed.
* **why one class per calc id.** The spec-to-result contract is asserted per id, so a
  shared class would make it impossible to tell which calc a result came from.

`python/src/azoth/core/result.py` re-exports these beside the hand-written enums, the
`_HasWarnings` mixin and the one record that is not a result.
"""

