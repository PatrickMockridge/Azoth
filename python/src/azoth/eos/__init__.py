"""Equations of state.

The third namespace, and the first that is not a correlation over pipe or wall
geometry. It exists because a cubic equation of state decomposes the same way every
other calculation here does - into constitutive coefficients, each with a published
source and a worked example - and the decomposition is worth having explicitly,
since a wrong coefficient is invisible downstream.

* :func:`pr_kappa` - the Peng-Robinson alpha-function coefficient
* :func:`pr_alpha_ab` - the alpha function and the reduced attraction parameters
* :func:`pr_departure` - fugacity coefficient and departure functions
* :func:`pr_z_factor` - the compressibility factor, the cubic's real roots
* :func:`pr_molar_volume` - molar volume, the one dimensional quantity here
* :func:`pr_mass_density` - mass density, and the end of the path to something useful

# Models

:func:`pure_saturation` is a *model* rather than a calculation: its spec fixes a
procedure rather than an equation, and it lives in ``specs/models/`` with a table
generated by ``tools/gen_models.py`` instead of ``gen_registry.py``. It composes the
kernels above and adds a search.
* :func:`prsv_kappa` - the Stryjek-Vera coefficient, for the same alpha function
* :func:`vdw1f_mix_binary` - van der Waals one-fluid mixing for a binary
* :func:`rachford_rice_binary` - the vapour fraction that solves Rachford-Rice

# Why the coefficients come first

The obvious shape for this namespace is one calc per equation of state, taking a
component and returning a Z factor. That shape hides the constants: a transposed
digit in the ``omega**2`` coefficient produces an equation that still runs, still
converges and is slightly wrong everywhere, and no check on the Z factor can see
it, because the Z factor is computed *from* the coefficient.

Splitting the constitutive coefficients out gives each one its own spec, its own
worked example and its own cross-language test. It also makes a modification cheap:
Peng-Robinson-Stryjek-Vera changes the temperature dependence of ``kappa`` and
nothing else, so under this decomposition it is one new calc rather than a fork of
the whole chain.

# Where the components come from

Nowhere, deliberately. There is **no component databank** in this library: every
pure-component constant - the acentric factor here, and the critical temperature
and pressure that go with it - is supplied by the caller. A databank is a
licensing and provenance problem as much as a data problem, and shipping one is a
decision worth making on its own rather than in passing. The same reasoning
already governs the fitting coefficients in :mod:`azoth.hydraulics`.

# Dimensionless by construction

Everything here works in reduced variables - ``Tr``, ``Pr``, and the dimensionless
coefficients that follow from them. ``A = 0.45724 * alpha * Pr / Tr**2`` needs no
gas constant, no pressure unit and no temperature unit, and the vapour-liquid
mixing rule is linear in ``A`` and ``B`` exactly as it is in ``a`` and ``b``. So
these functions take and return ``pint`` quantities that carry no unit, and the
dimensional conversion happens once, at the boundary, where it can be tested once.

# Which implementation answers

As in every other namespace, each function dispatches to the Rust extension when it
is built and to :mod:`azoth.eos.reference` otherwise. Both are always reachable -
see :func:`azoth.backends` and :func:`azoth.use_backend`.
"""

from __future__ import annotations

from azoth._dispatch import resolve
from azoth.core.result import (
    PrAlphaAbResult,
    PrDepartureResult,
    PrKappaResult,
    PrMassDensityResult,
    PrMolarVolumeResult,
    PrsvKappaResult,
    PrZFactorResult,
    PureSaturationResult,
    RachfordRiceBinaryResult,
    Vdw1fMixBinaryResult,
)
from azoth.core.units import Q

__all__ = [
    "pr_alpha_ab",
    "pr_departure",
    "pr_kappa",
    "pr_mass_density",
    "pr_molar_volume",
    "pr_z_factor",
    "prsv_kappa",
    "pure_saturation",
    "rachford_rice_binary",
    "vdw1f_mix_binary",
]

_PR_KAPPA = "eos.pr_kappa"
_PR_MOLAR_VOLUME = "eos.pr_molar_volume"
_PR_MASS_DENSITY = "eos.pr_mass_density"
_PURE_SATURATION = "eos.pure_saturation"
_PR_ALPHA_AB = "eos.pr_alpha_ab"
_PR_DEPARTURE = "eos.pr_departure"
_PR_Z_FACTOR = "eos.pr_z_factor"
_PRSV_KAPPA = "eos.prsv_kappa"
_VDW1F_MIX_BINARY = "eos.vdw1f_mix_binary"
_RACHFORD_RICE_BINARY = "eos.rachford_rice_binary"


def pr_kappa(omega: float) -> PrKappaResult:
    """The Peng-Robinson alpha-function coefficient for a pure component.

    ``omega`` is the acentric factor, and a plain float rather than a ``pint``
    quantity because it is genuinely dimensionless - the same rule that makes
    ``Re``, ``f`` and ``epsilon/D`` plain floats in the hydraulics calcs. A
    ``kappa`` below zero comes back carrying ``OUT_OF_VALID_RANGE`` rather than
    raising: the coefficient is negative for any acentric factor below about
    -0.2334, which helium is, and a value out of range is still a value.

    See :func:`azoth.eos.reference.pr_kappa`.
    """
    return resolve(_PR_KAPPA)(omega=omega)  # type: ignore[no-any-return]


def pr_alpha_ab(kappa: float, Tr: float, Pr: float) -> PrAlphaAbResult:
    """The Peng-Robinson alpha function and the reduced attraction parameters.

    ``a_reduced`` is the cubic's ``A`` and ``b_reduced`` its ``B`` - the form the
    equation of state is solved in, which needs no gas constant and no unit.

    Raises:
        OutOfRangeError: if ``Tr <= 0`` or ``Pr <= 0``.

    See :func:`azoth.eos.reference.pr_alpha_ab`.
    """
    return resolve(_PR_ALPHA_AB)(kappa=kappa, Tr=Tr, Pr=Pr)  # type: ignore[no-any-return]


def pr_z_factor(a_reduced: float, b_reduced: float) -> PrZFactorResult:
    """The Peng-Robinson compressibility factor, for one state.

    Returns the smallest and largest *admissible* real roots, where admissible means
    ``z > b_reduced``, plus how many there were. The middle root is deliberately not
    returned: it is a root of the polynomial and not a state the equation describes.

    Raises:
        OutOfRangeError: if ``b_reduced <= 0`` or ``a_reduced < 0``.

    See :func:`azoth.eos.reference.pr_z_factor`.
    """
    return resolve(_PR_Z_FACTOR)(a_reduced=a_reduced, b_reduced=b_reduced)  # type: ignore[no-any-return]


def prsv_kappa(omega: float, Tr: float, kappa1: float) -> PrsvKappaResult:
    """The PRSV alpha-function coefficient for a pure component.

    ``kappa1`` is the pure-compound parameter PRSV adds, and **this library ships no
    values for it** - a table of fitted parameters is the databank this library
    deliberately has none of. Passing a real one is the caller's job, and passing
    zero does not reproduce Peng-Robinson.

    Raises:
        OutOfRangeError: if ``Tr <= 0``.

    See :func:`azoth.eos.reference.prsv_kappa`.
    """
    return resolve(_PRSV_KAPPA)(omega=omega, Tr=Tr, kappa1=kappa1)  # type: ignore[no-any-return]


def pr_departure(
    a_reduced: float, b_reduced: float, z: float, kappa: float, Tr: float
) -> PrDepartureResult:
    """The Peng-Robinson fugacity coefficient and departure functions.

    ``kappa`` may come from :func:`pr_kappa` or :func:`prsv_kappa` - this calc uses it
    only through the logarithmic derivative of the alpha function, which both
    correlations feed.

    Raises:
        OutOfRangeError: if ``b_reduced <= 0`` or ``z <= b_reduced``.

    See :func:`azoth.eos.reference.pr_departure`.
    """
    return resolve(_PR_DEPARTURE)(  # type: ignore[no-any-return]
        a_reduced=a_reduced, b_reduced=b_reduced, z=z, kappa=kappa, Tr=Tr
    )


def vdw1f_mix_binary(
    z1: float, a1: float, a2: float, b1: float, b2: float, k12: float
) -> Vdw1fMixBinaryResult:
    """The van der Waals one-fluid mixture parameters for a binary.

    ``k12`` is the binary interaction parameter, and **this library ships no values
    for it** - a table of fitted binary parameters is the databank it deliberately
    does not have.

    Raises:
        OutOfRangeError: if ``z1`` is outside ``[0, 1]`` or the resulting ``a_mix``
            would be negative.

    See :func:`azoth.eos.reference.vdw1f_mix_binary`.
    """
    return resolve(_VDW1F_MIX_BINARY)(  # type: ignore[no-any-return]
        z1=z1, a1=a1, a2=a2, b1=b1, b2=b2, k12=k12
    )


def rachford_rice_binary(z1: float, K1: float, K2: float) -> RachfordRiceBinaryResult:
    """The vapour fraction that solves the Rachford-Rice equation for two components.

    A ``beta`` outside ``[0, 1]`` comes back carrying ``OUT_OF_VALID_RANGE`` rather
    than raising: it says the feed is single phase, which is a real answer.

    Raises:
        OutOfRangeError: if ``z1`` is outside ``[0, 1]``, either K-value is not
            positive, or either equals 1.

    See :func:`azoth.eos.reference.rachford_rice_binary`.
    """
    return resolve(_RACHFORD_RICE_BINARY)(z1=z1, K1=K1, K2=K2)  # type: ignore[no-any-return]


def pr_molar_volume(z: float, T: Q, P: Q) -> PrMolarVolumeResult:
    """Molar volume at a state, from its compressibility factor.

    Either admissible root may be passed to ``z`` - the vapour one gives the vapour
    volume and the liquid one the liquid volume.

    Raises:
        OutOfRangeError: if ``z <= 0`` or if ``T`` or ``P`` is not positive.

    See :func:`azoth.eos.reference.pr_molar_volume`.
    """
    return resolve(_PR_MOLAR_VOLUME)(z=z, T=T, P=P)  # type: ignore[no-any-return]


def pr_mass_density(M: Q, v: Q) -> PrMassDensityResult:
    """Mass density from a molar mass and a molar volume.

    ``M`` is the caller's - this library ships no component data - and note the unit
    is ``kg/mol``, not the ``g/mol`` tables usually quote.

    Raises:
        OutOfRangeError: if ``M <= 0`` or ``v <= 0``.

    See :func:`azoth.eos.reference.pr_mass_density`.
    """
    return resolve(_PR_MASS_DENSITY)(M=M, v=v)  # type: ignore[no-any-return]


def pure_saturation(Tc: Q, Pc: Q, omega: float, T: Q) -> PureSaturationResult:
    """The saturation pressure of a pure component at a temperature.

    ``T`` must be below ``Tc`` - above the critical temperature there is no saturation
    pressure, and this refuses rather than returning an extrapolation.

    Raises:
        OutOfRangeError: if ``T``, ``Tc`` or ``Pc`` is not positive, or if
            ``T >= Tc``.
        SolverNotConvergedError: if the search hits its cap.

    See :func:`azoth.eos.reference.pure_saturation`.
    """
    return resolve(_PURE_SATURATION)(Tc=Tc, Pc=Pc, omega=omega, T=T)  # type: ignore[no-any-return]
