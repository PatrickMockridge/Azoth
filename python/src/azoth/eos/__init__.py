def capillary_dew_point(
    mixture: Mixture,
    P: Q,
    y: list[float],
    pore_radius: Q,
    contact_angle: Q | None = None,
    surface_tension: Q | None = None,
) -> CapillaryDewPointResult:
    """The dew point of a vapour held in a pore: the same boundary, on a curved interface.

    Young-Laplace puts the liquid inside a pore at a pressure above the vapour outside it by
    ``2 sigma cos(theta) / r``, and the Kelvin equation shifts every K-value by
    ``exp(-Vm_L dP_cap / (R T))``. The incipient liquid is stabilised, so the dew point moves
    **up** - which is the direction that matters for condensation in tight rock::

        r = azoth.eos.capillary_dew_point(fluid, P=q(20, "bar"), y=[0.5, 0.5],
        ...                               pore_radius=q(1e-8, "m"))
        r.temperature, r.capillary_pressure

    **All three curvature inputs are quantities**, like every declared input in this library: a
    bare number where a unit is expected is the mistake the units layer exists to make
    impossible. ``pore_radius`` is a length - the radii that matter are nanometres
    (``q(10, "nm")``) - and ``contact_angle`` is an angle, zero being a perfectly wetting
    liquid and ``q(90, "deg")`` non-wetting.

    ``surface_tension`` is the caller's, not the mixture's. It defaults to ``q(0.005, "N/m")``,
    which is NeqSim's own fallback, and ``eos.parachor_surface_tension`` computes one from the
    two phases. Reading a correlation inside a model whose other inputs are all stated would
    hide which was used, so it is stated here.

    Raises:
        InvalidInputError: if ``y`` is not a composition, or the contact angle is not finite.
        OutOfRangeError: if ``P`` is not positive, ``pore_radius`` is not positive,
            ``surface_tension`` is negative, or the mixture has no dew point at this pressure.

    See :func:`azoth.eos.reference.capillary_dew_point`.
    """
    return resolve(_CAPILLARY_DEW_POINT)(  # type: ignore[no-any-return]
        mixture=mixture,
        P=P,
        y=y,
        pore_radius=pore_radius,
        contact_angle=(from_si(0.0, "rad") if contact_angle is None else contact_angle),
        surface_tension=(from_si(0.005, "N/m") if surface_tension is None else surface_tension),
    )


def ideal_gas_cp(
    cp_a: float, cp_b: float, cp_c: float, cp_d: float, cp_e: float, T: Q
) -> IdealGasCpResult:
    """The ideal-gas heat capacity at a temperature, from a caller-supplied polynomial.

    ``cp = cp_a + cp_b*T + cp_c*T**2 + cp_d*T**3 + cp_e*T**4``, dimensional throughout:
    the coefficients carry the powers of temperature in their units, so ``cp_a`` is a
    heat capacity and ``cp_b`` is one per kelvin. Those are the units the ``CPA``-``CPE``
    columns of NeqSim's ``COMP.csv`` are stored in, which is where they come from.

    ``T`` must lie inside the range the coefficients were fitted over, and that is not
    checked. A polynomial evaluated outside it turns over, ``cp`` goes negative, and
    the result carries ``OUT_OF_VALID_RANGE`` - which is the case this catches, not the
    more likely one where the value is simply a few per cent wrong.

    Raises:
        OutOfRangeError: if ``T`` is not positive.

    See :func:`azoth.eos.reference.ideal_gas_cp`.
    """
    return resolve(_IDEAL_GAS_CP)(  # type: ignore[no-any-return]
        cp_a=cp_a, cp_b=cp_b, cp_c=cp_c, cp_d=cp_d, cp_e=cp_e, T=T
    )


def molar_enthalpy_entropy(
    mixture: Mixture,
    ideal_gas: IdealGasModel,
    T: Q,
    P: Q,
    z: list[float],
    compressibility: float,
) -> MolarEnthalpyEntropyResult:
    """The absolute molar enthalpy and entropy of a mixture at a state.

    ``H = H_ig(T_ref) + integral Cp dT + H_dep`` and
    ``S = S_ig(T_ref) + integral Cp/T dT - R ln(P/P_ref) - R sum z_i ln z_i + S_dep``.

    **``ideal_gas`` carries the datum and nothing checks it.** Two enthalpies computed
    from different reference values are not comparable, and subtracting them gives a
    plausible number rather than an error - so a caller computing a difference must
    know both calls used the same one.

    ``compressibility`` is the cubic's root for the phase wanted, taken as given rather
    than solved for: which root describes the phase is a choice, and a caller holding a
    ``Z`` from :func:`pr_z_factor` or from :func:`pt_flash` has already made it.

    Raises:
        InvalidInputError: if the composition or any ideal-gas vector is the wrong
            length, or if ``z`` is not a composition.
        OutOfRangeError: if a temperature or pressure is not positive, or if the root
            is not admissible.

    See :func:`azoth.eos.reference.molar_enthalpy_entropy`.
    """
    return resolve(_MOLAR_ENTHALPY_ENTROPY)(  # type: ignore[no-any-return]
        mixture=mixture, ideal_gas=ideal_gas, T=T, P=P, z=z, compressibility=compressibility
    )


