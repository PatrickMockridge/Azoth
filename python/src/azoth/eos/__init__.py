def bubble_pressure(mixture: Mixture, T: Q, x: list[float]) -> BubblePressureResult:
    """The pressure at which a liquid of composition ``x`` first gives off vapour.

    The companion of :func:`dew_pressure`: the same iteration with the other phase
    held, which is why the argument is ``x`` here and ``y`` there. A shared name
    would have to be ``z``, which means the feed and would be wrong.

    ``x`` is the liquid's composition and is taken as given - whether that liquid is
    stable is not asked.

    Raises:
        InvalidInputError: if the mixture has one component - a pure component's
            bubble point is its saturation pressure, which :func:`pure_saturation`
            computes - or if ``x`` is not a composition.
        OutOfRangeError: if ``T`` is not positive, or if the mixture has no bubble
            point at this temperature. That is a real state and not a solver
            failure: a mixture above its critical condition has neither a bubble nor
            a dew point, and the error names ``min_t_over_tc``.

    See :func:`azoth.eos.reference.bubble_pressure`.
    """
    return resolve(_BUBBLE_PRESSURE)(mixture=mixture, T=T, x=x)  # type: ignore[no-any-return]


def critical_point(mixture: Mixture, z: list[float]) -> CriticalPointResult:
    """The critical point of a mixture of composition ``z``.

    ``z`` is the composition of the single phase whose critical point is wanted, not a
    feed being split - so unlike the flash's, this model does not decide what happens
    to it. Whether that composition could exist at the returned state is a different
    question and is not asked.

    The result is a **mixture** critical point, and its ``Z_c`` is what shows it: a pure
    component's is ``(1 - omega_b)/3`` exactly, and a mixture's varies with composition.
    Solving ``dP/dV = d2P/dV2 = 0`` instead - the obvious route - gives that same
    constant for every mixture there is, which is why this does not use it.

    Raises:
        InvalidInputError: if ``z`` is the wrong length, has a negative entry, or does
            not sum to one. It is checked rather than renormalised.
        SolverNotConvergedError: if the two conditions do not reach the tolerance in
            the spec's iteration cap. A critical point that is nearly one is not one.
        OutOfRangeError: if the state the iteration converged on is not a state.

    See :func:`azoth.eos.reference.critical_point`.
    """
    return resolve(_CRITICAL_POINT)(mixture=mixture, z=z)  # type: ignore[no-any-return]


def dew_pressure(mixture: Mixture, T: Q, y: list[float]) -> DewPressureResult:
    """The pressure at which a vapour of composition ``y`` first condenses.

    Raises:
        InvalidInputError: if the mixture has one component, or if ``y`` is not a
            composition.
        OutOfRangeError: if ``T`` is not positive, or if the mixture has no dew point
            at this temperature.

    See :func:`azoth.eos.reference.dew_pressure`.
    """
    return resolve(_DEW_PRESSURE)(mixture=mixture, T=T, y=y)  # type: ignore[no-any-return]


def ideal_gas_cp(a: float, b: float, c: float, d: float, T: Q) -> IdealGasCpResult:
    """The ideal-gas heat capacity at a temperature, from a caller-supplied polynomial.

    ``Cp/R = a + b*theta + c*theta**2 + d*theta**3`` with ``theta = T/(1000 K)``, so
    the four coefficients are dimensionless and a published table's printed numbers go
    in unchanged - see :func:`azoth.eos.reference.ideal_gas_cp` for the derivation of
    that substitution.

    **This library ships no heat-capacity coefficients.** They are per-component fitted
    data, which is the databank this library deliberately has none of.

    ``T`` must lie inside the range the coefficients were fitted over, and that is not
    checked. A polynomial evaluated outside it turns over, ``cp`` goes negative, and
    the result carries ``OUT_OF_VALID_RANGE`` - which is the case this catches, not the
    more likely one where the value is simply a few per cent wrong.

    Raises:
        OutOfRangeError: if ``T`` is not positive.

    See :func:`azoth.eos.reference.ideal_gas_cp`.
    """
    return resolve(_IDEAL_GAS_CP)(a=a, b=b, c=c, d=d, T=T)  # type: ignore[no-any-return]


def molar_enthalpy_entropy(
    mixture: Mixture,
    ideal_gas: IdealGasModel,
    T: Q,
    P: Q,
    z: list[float],
    compressibility: float,
) -> MolarEnthalpyEntropyResult:
    """The absolute molar enthalpy and entropy of a mixture at a state.

    ``H = H_ig(T_ref) + integral Cp dT + H_dep`` and
    ``S = S_ig(T_ref) + integral Cp/T dT - R ln(P/P_ref) - R sum z_i ln z_i + S_dep``.

    **``ideal_gas`` carries the datum and nothing checks it.** Two enthalpies computed
    from different reference values are not comparable, and subtracting them gives a
    plausible number rather than an error - so a caller computing a difference must
    know both calls used the same one.

    ``compressibility`` is the cubic's root for the phase wanted, taken as given rather
    than solved for: which root describes the phase is a choice, and a caller holding a
    ``Z`` from :func:`pr_z_factor` or from :func:`pt_flash` has already made it.

    Raises:
        InvalidInputError: if the composition or any ideal-gas vector is the wrong
            length, or if ``z`` is not a composition.
        OutOfRangeError: if a temperature or pressure is not positive, or if the root
            is not admissible.

    See :func:`azoth.eos.reference.molar_enthalpy_entropy`.
    """
    return resolve(_MOLAR_ENTHALPY_ENTROPY)(  # type: ignore[no-any-return]
        mixture=mixture, ideal_gas=ideal_gas, T=T, P=P, z=z, compressibility=compressibility
    )


def pt_flash(mixture: Mixture, T: Q, P: Q, z: list[float]) -> PtFlashResult:
    """The two-phase flash of a mixture at a temperature and pressure.

    The deliverable of this namespace: how much of a feed is vapour, what the two
    phases are made of, and the fugacity coefficients that make it so::

        fluid = azoth.eos.mixture(
            [propane, butane], kij={(0, 1): 0.0}
        )
        r = azoth.eos.pt_flash(fluid, T=q(330, "K"), P=q(2.5e6, "Pa"), z=[0.6, 0.4])
        r.beta, r.x, r.y, r.phase

    ``z`` is **checked rather than renormalised** - a composition that does not sum
    to one is a mistake, and silently correcting it would make it invisible in every
    number downstream.

    **Read ``phase``, not ``beta``.** ``beta`` is ``None`` where there is no vapour
    fraction to report, which is one of two things: the feed has no two-phase
    solution at all (every K-value on the same side of one, and the result says
    ``all_liquid`` or ``all_vapour``), or the iteration converged to ``x = y = z``
    and the model cannot tell which single phase the feed is (``TRIVIAL``). A
    ``beta`` outside ``[0, 1]`` but present is the negative flash - a real reading,
    reported with ``OUT_OF_VALID_RANGE``.

    There is **no stability test**: a converged split is a stationary point of the
    flash equations, not a proof that the feed was unstable. See the model spec.

    Raises:
        InvalidInputError: if ``z`` is the wrong length, has a negative entry, or
            does not sum to one, or if the mixture's ``kij`` is malformed.
        OutOfRangeError: if ``T`` or ``P`` is not positive.
        SolverNotConvergedError: if the iteration hits its cap.

    See :func:`azoth.eos.reference.pt_flash`.
    """
    return resolve(_PT_FLASH)(mixture=mixture, T=T, P=P, z=z)  # type: ignore[no-any-return]


def ph_flash(
    mixture: Mixture, ideal_gas: IdealGasModel, P: Q, H: Q, z: list[float]
) -> PhFlashResult:
    """The temperature a mixture reaches at a pressure when given a duty.

    The model the process layer needs. A heater, a cooler, a compressor, a valve: each
    knows the pressure a stream leaves at and the energy it added, and none of them
    knows the temperature that results. This is that temperature, and the phase split
    at it::

        r = azoth.eos.ph_flash(fluid, ig, P=q(20, "bar"), H=q(-6723.0, "J/mol"), z=[0.6, 0.4])
        r.T, r.phase, r.beta

    **``H`` is a difference from the datum ``ideal_gas`` carries**, not an absolute
    quantity. Two calls with different reference values are not comparable, and their
    difference is a plausible number rather than an error - the same caveat
    :func:`molar_enthalpy_entropy` carries, for the same reason.

    **Read ``phase``, not ``beta``.** ``beta`` is ``None`` for a single-phase feed.
    That is not a missing value: the flash reports an *extrapolated* split below the
    bubble point or above the dew point - values like 1.9 are ordinary - and it is not
    the vapour fraction of anything.

    Raises:
        InvalidInputError: if ``z`` or any ideal-gas vector is the wrong length, or if
            ``z`` is not a composition.
        OutOfRangeError: if ``P`` is not positive, or a range check on the answer fails.
        SolverNotConvergedError: if no temperature on the model's bracket produces the
            requested enthalpy, or if the bisection hits its cap.

    See :func:`azoth.eos.reference.ph_flash`.
    """
    return resolve(_PH_FLASH)(  # type: ignore[no-any-return]
        mixture=mixture, ideal_gas=ideal_gas, P=P, H=H, z=z
    )


def ps_flash(
    mixture: Mixture, ideal_gas: IdealGasModel, P: Q, S: Q, z: list[float]
) -> PsFlashResult:
    """The temperature a mixture reaches at a pressure when expanded isentropically.

    The companion to :func:`ph_flash`, for the unit operations that conserve entropy
    rather than energy: a compressor or an expander assumed ideal, a turbine, a nozzle::

        r = azoth.eos.ps_flash(fluid, ig, P=q(20, "bar"), S=q(-39.078, "J/(mol*K)"), z=[0.6, 0.4])
        r.T, r.phase, r.beta

    **``S`` is a difference from the datum ``ideal_gas`` carries**, not an absolute
    quantity - the same caveat :func:`molar_enthalpy_entropy` carries, for the same
    reason.

    The two phases are summed at *their own* compositions, so the result carries the
    entropy of mixing. That is the physically correct assembly and it is not optional:
    summing the phases at the feed composition would conserve entropy across a phase
    change, which is wrong.

    Raises:
        InvalidInputError: if ``z`` or any ideal-gas vector is the wrong length, or if
            ``z`` is not a composition.
        OutOfRangeError: if ``P`` is not positive, or a range check on the answer fails.
        SolverNotConvergedError: if no temperature on the model's bracket produces the
            requested entropy, or if the bisection hits its cap.

    See :func:`azoth.eos.reference.ps_flash`.
    """
    return resolve(_PS_FLASH)(  # type: ignore[no-any-return]
        mixture=mixture, ideal_gas=ideal_gas, P=P, S=S, z=z
    )


def stability_test(mixture: Mixture, T: Q, P: Q, z: list[float]) -> StabilityTestResult:
    """Whether a mixture at a temperature and pressure is stable as a single phase.

    The question :func:`pt_flash` cannot ask. Successive substitution finds *a*
    stationary point; whether the feed was stable to begin with is a different
    question, and a flash that converges to ``x = y = z`` has demonstrated that its
    own starting point was not a split - not that the feed is single phase. This is
    the model that answers it, by Michelsen's tangent-plane criterion: two trial
    phases, seeded from Wilson K-values, are each iterated to a stationary point of
    the tangent-plane distance, and the feed is unstable if either lands below the
    tangent plane through the feed::

        r = azoth.eos.stability_test(fluid, T=q(330, "K"), P=q(25, "bar"), z=[0.6, 0.4])
        r.verdict, r.tm, r.iterations

    **``stable`` means these two trials found nothing, not that no split exists.**
    Both trials are placed by a gas-liquid correlation, so a feed unstable to a
    *liquid-liquid* split comes back ``stable`` and nothing here detects it. And
    ``unstable`` says a split exists without saying what it is or how many phases it
    has - that is :func:`pt_flash`'s question, and for three phases neither model
    answers it.

    ``tm`` and ``w`` are one entry per trial in a fixed order - **vapour-like first**,
    then liquid-like - and two entries always, so a caller reads ``tm[0]`` as the
    vapour-like trial. A row of ``w`` equal to the feed is a trivial stationary
    point: the trial found the feed's own and says nothing about whether another
    exists. Its ``tm`` is zero to rounding, which is why the instability threshold is
    ``-1e-8`` rather than zero - and why the verdict cannot be read off a single
    distance.

    ``z`` is **checked rather than renormalised**, as everywhere in this namespace.

    Raises:
        InvalidInputError: if ``z`` is the wrong length, has a negative entry, or
            does not sum to one, or if the mixture's ``kij`` is malformed.
        OutOfRangeError: if ``T`` or ``P`` is not positive.
        SolverNotConvergedError: if a trial hits its cap. A tangent-plane distance
            bounds stability only at a stationary point, so an unconverged trial is
            an error rather than a trial quietly discarded.

    See :func:`azoth.eos.reference.stability_test`.
    """
    return resolve(_STABILITY_TEST)(mixture=mixture, T=T, P=P, z=z)  # type: ignore[no-any-return]


def pure_saturation(Tc: Q, Pc: Q, omega: float, T: Q) -> PureSaturationResult:
    """The saturation pressure of a pure component at a temperature.

    ``T`` must be below ``Tc`` - above the critical temperature there is no saturation
    pressure, and this refuses rather than returning an extrapolation.

    Raises:
        OutOfRangeError: if ``T``, ``Tc`` or ``Pc`` is not positive, or if
            ``T >= Tc``.
        SolverNotConvergedError: if the search hits its cap.

    See :func:`azoth.eos.reference.pure_saturation`.
    """
    return resolve(_PURE_SATURATION)(Tc=Tc, Pc=Pc, omega=omega, T=T)  # type: ignore[no-any-return]
