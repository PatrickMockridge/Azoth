#!/usr/bin/env python3
"""Generate the process models' `CalcResult` blocks.

Every `crates/azoth-process/src/models/*.rs` carries one `impl CalcResult for <Struct>`: a
`CALC_ID`, a `FIELDS` list and the `warnings` accessor. None of it is a decision - the id is the
spec's own, the fields are the struct's `pub` fields in declaration order, and the accessor is the
one field every result has.

    python tools/gen_rust_model_records.py            # write
    python tools/gen_rust_model_records.py --check    # fail if the tree is not what this emits
    python tools/gen_rust_model_records.py --survey   # what it covers, and what it leaves

The structs and the kernels stay where they are: `tools/provenance.py` derives each kernel's Rust
path from the file it sits in, so moving a struct breaks
`test_every_registered_id_resolves_to_its_spec_and_kernels`. Only the block moves.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rust_index

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "azoth-process" / "src" / "model_records_gen.rs"

#: The field every result carries, and the accessor `CalcResult` asks for.
WARNINGS = "warnings"

HEADER = '''//! The process models' `CalcResult` blocks, emitted from the specs and the structs.
//!
//! Generated by `tools/gen_rust_model_records.py` - **do not edit by hand.** Each block is a
//! function of two declarations that already exist: `CALC_ID` is the spec's own id and `FIELDS`
//! is the struct's `pub` fields in declaration order, which is what
//! `test_registry_contract` holds the published result to.
//!
//! The structs and the kernels stay in `models/*.rs`: `tools/provenance.py` derives a kernel's
//! Rust path from the file it sits in, so producing them here would break
//! `test_every_registered_id_resolves_to_its_spec_and_kernels`.

use azoth_core::{CalcResult, Warning};

'''


def struct_name(result: rust_index.ResultType) -> str:
    """The struct this block is written for, the last segment of its item path."""
    return result.item_path.rpartition("::")[2]


def module_path(calc_id: str) -> str:
    """`crate::models::<module>`, from the id's own last segment."""
    return f"crate::models::{calc_id.rpartition('.')[2]}"


def emit_block(result: rust_index.ResultType) -> str:
    """One `impl CalcResult` block."""
    name = struct_name(result)
    fields = [field for field, _ in result.fields]
    if fields[-1] != WARNINGS:
        raise ValueError(f"{result.calc_id}: last field is {fields[-1]!r}, not `{WARNINGS}`")
    body = "\n".join(f'        "{field}",' for field in fields)
    return (
        f"impl CalcResult for {name} {{\n"
        f'    const CALC_ID: &\'static str = "{result.calc_id}";\n'
        f"    const FIELDS: &'static [&'static str] = &[\n"
        f"{body}\n"
        f"    ];\n"
        f"\n"
        f"    fn warnings(&self) -> &[Warning] {{\n"
        f"        &self.{WARNINGS}\n"
        f"    }}\n"
        f"}}\n"
    )


def process_results() -> tuple[list[rust_index.ResultType], list[str]]:
    """`(covered, refused)` - the process ids this can write a block for, and why not."""
    covered, left = [], []
    for result in rust_index.result_types():
        if not result.calc_id.startswith("process."):
            continue
        try:
            fields = [field for field, _ in result.fields]
            if not fields or fields[-1] != WARNINGS:
                raise ValueError(f"last field is {fields[-1] if fields else None!r}")
        except ValueError as why:
            left.append(f"{result.calc_id}: {why}")
            continue
        covered.append(result)
    return covered, left


def emit() -> str:
    """The whole file: a header, the imports, and one block per covered id."""
    covered, _ = process_results()
    imports = "\n".join(
        f"use {module_path(r.calc_id)}::{struct_name(r)};" for r in covered
    )
    blocks = "\n".join(emit_block(r) for r in covered)
    return f"{HEADER}{imports}\n\n\n{blocks}"


def rustfmt(text: str) -> str:
    """Rustfmt's own output, refused rather than fallen back on (`gen_palette`'s policy)."""
    done = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=text, capture_output=True, text=True, check=False,
    )
    if done.returncode != 0:
        raise SystemExit(f"rustfmt failed: {done.stderr}")
    return done.stdout


def main() -> int:
    if "--survey" in sys.argv:
        covered, left = process_results()
        print(f"covered: {len(covered)}")
        for why in left:
            print(f"   left hand-written: {why}")
        return 0

    text = rustfmt(emit())
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"::error::{OUT.relative_to(ROOT)} is not what the generator emits")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
