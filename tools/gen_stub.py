#: How a Python result field's type is spelled in the stub.
#:
#: `Q` becomes `Qty` because that is what crosses the boundary; an enum becomes `str`
#: because the bridge rebuilds it. A `tuple[X, ...]` is a `list[X]` on the Rust side, so
#: the stub says `list` - the shape a caller gets, not the shape the dataclass stores.
SCALARS = {"float": "float", "int": "int", "bool": "bool", "str": "str", "Q": "Qty"}
ENUMS = {
    "Phase",
    "RootStructure",
    "StabilityVerdict",
    "TpMultiflashSeed",
    "FlowRegime",
    "HenryStatus",
    "HydrateStructure",
}


def stub_type(annotation: Any) -> str:
    """How one result field's type is spelled in the stub."""
    if annotation is None or annotation is type(None):
        return "None"
    name = getattr(annotation, "__name__", None)
    if name in SCALARS:
        return SCALARS[name]
    if name in ENUMS:
        return "str"

    origin = get_origin(annotation)
    if origin in (tuple, list, set):
        args = get_args(annotation)
        return f"list[{stub_type(args[0] if args else Any)}]"

    if type(annotation).__name__ == "UnionType":
        parts = get_args(annotation)
        rendered = stub_type(next(part for part in parts if part is not type(None)))
        if any(part is type(None) for part in parts):
            return f"{rendered} | None"
        return rendered

    return str(getattr(annotation, "__name__", annotation))


def parameter_type(declaration: dict[str, Any]) -> str:
    """How one declared input is spelled in the stub."""
    kind = declaration.get("type", "quantity")
    if kind == "fitting_list":
        return "list[str]"
    if kind == "vector_string":
        # A name vector, which `model.schema.json` has admitted as an input all along: the case
        # table carries it as `TestCase::lists` and the extension takes a `Vec<String>`, so the
        # stub is the same shape a fitting list is.
        return "list[str]"
    if kind == "vector":
        return "list[float]"
    if kind == "matrix":
        return "list[list[float]]"
    if kind == "boolean":
        return "bool"
    if kind in ("enum", "string"):
        return "str"
    if kind == "record_list":
        # **The row's own name, which `render_vocabulary` declares from the same `fields`
        # block.** An input row is built by a caller, so the mapping's shape and the spec's
        # declaration of it have to be one statement; naming the shape here and generating
        # it there is that statement, and a stub that spelled `list[dict[str, float]]`
        # instead would type-check a row with the wrong fields in it.
        row = declaration.get("row_type")
        if row is None:
            raise SystemExit(
                "gen_stub: a `record_list` input declares no `row_type`, so the mapping "
                "type its callers build has no name to be declared under"
            )
        return f"list[{row}]"
    return "float"


def record_field_type(declared: dict[str, Any]) -> str:
    """How one field of an input row is spelled in the stub.

    **The stub describes what reaches the extension, which is a mapping of SI magnitudes.**
    `input_records_to_si` has already converted every dimensioned field, so a quantity field
    is a `float` here whether the caller handed over a quantity or a bare number - the same
    reason `ComponentArguments` is all floats.
    """
    base = {"boolean": "bool", "enum": "str", "string": "str"}.get(
        declared.get("type", "quantity"), "float"
    )
    return f"{base} | None" if declared.get("optional", False) else base


def record_rows() -> dict[str, dict[str, Any]]:
    """Every `record_list` input's row, keyed by the name its `row_type` gives it.

    Generated from the specs rather than listed, because a row's fields *are* the spec's
    `fields` block: the mapping is what the bridge hands the extension, so a hand-kept copy
    of the declaration would be a second place the row can change.
    """
    rows: dict[str, dict[str, Any]] = {}
    for model in MODELS:
        for input_name, declaration in model["inputs"].items():
            if declaration.get("type") != "record_list":
                continue
            row = declaration.get("row_type")
            if not row:
                raise SystemExit(
                    f"gen_stub: {model['id']}.{input_name} is a record_list and declares "
                    f"no `row_type`, so its mapping type has no name to be declared under"
                )
            if row in rows and rows[row] != declaration["fields"]:
                raise SystemExit(
                    f"gen_stub: `{row}` is declared by two `fields` blocks that differ; one "
                    f"row type is one shape"
                )
            rows[row] = declaration["fields"]
    return rows


@functools.lru_cache(maxsize=1)
def record_output_rows() -> dict[str, dict[str, Any]]:
    """Every `record_list` *output*'s row, keyed by the kernel struct it is carried as.

    The mirror of `record_rows`, and the same claim: a row's fields *are* the spec's `fields`
    block, so a hand-kept copy of the declaration is a second place the row can change. What
    differs is the direction. An input row is built in Python and read in Rust, so its stub
    type is a `TypedDict` and its Rust type derives `FromPyObject`; an output row is built in
    Rust and read in Python, so its stub type is a class and its Rust type is a `#[pyclass]`.

    **Keyed by the kernel struct's own name**, which is the name both sides already carry: the
    element is read out of the result's `Vec<X>`, the same reading `rust_index.result_types`
    makes. A `row_type` on an output would be a second registration of what the Rust struct
    declares, which is the rule `rust_index` states for a result type.

    `[*CALCS, *MODELS]` rather than the models alone, because a calc can carry one too. **The
    value is the spec's own output declaration**, not its `fields` block alone, so the row's
    description travels with its shape.
    """
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    try:
        import rust_index
    finally:
        sys.path.pop(0)

    by_id = {result.calc_id: result for result in rust_index.result_types()}
    rows: dict[str, dict[str, Any]] = {}
    for spec in [*CALCS, *MODELS]:
        result = by_id.get(spec["id"])
        if result is None:
            continue
        carried = dict(zip(result.public_fields, result.rust_field_types, strict=True))
        for output, declaration in (spec.get("outputs") or {}).items():
            if declaration.get("type") != "record_list":
                continue
            ty = carried.get(output)
            if ty is None or not (ty.startswith("Vec<") and ty.endswith(">")):
                raise SystemExit(
                    f"gen_stub: {spec['id']}.{output} is a record_list and the result's "
                    f"`{output}` is {ty!r}, not a `Vec<Row>`; an output row's element is the "
                    "kernel struct it is carried as"
                )
            element = ty[len("Vec<") : -1]
            if element in rows and rows[element]["fields"] != declaration["fields"]:
                raise SystemExit(
                    f"gen_stub: `{element}` is declared by two `fields` blocks that differ; one "
                    f"row type is one shape"
                )
            rows[element] = declaration

    clash = sorted(set(rows) & set(record_rows()))
    if clash:
        raise SystemExit(
            f"gen_stub: {clash} name both a `record_list` input row and a `record_list` output "
            "row; a `TypedDict` and a class cannot be declared under one name"
        )
    return rows


def render_parameter(name: str, declaration: dict[str, Any]) -> str:
    base = parameter_type(declaration)
    if declaration.get("optional", False):
        return f"{name}: {base} | None = None"
    return f"{name}: {base}"


def ordered_parameters(inputs: Mapping[str, dict[str, Any]]) -> list[tuple[str, dict[str, Any]]]:
    """A model's declared inputs, **with the optional ones last**.

    Python has no syntax for a parameter with a default in front of one without, so a
    spec that declares an optional input anywhere but last cannot be spelled as a
    signature at all - and `process.separator`'s `gas_in_liquid` after `heat_input` was
    exactly that, emitted as a stub that did not parse. The spec's own order is the
    domain's order and is worth keeping; the *signature's* order is a language
    constraint, so it is applied here rather than imposed on every spec.
    """
    items = list(inputs.items())
    return [item for item in items if not item[1].get("optional", False)] + [
        item for item in items if item[1].get("optional", False)
    ]


def render_result_class(calc_id: str) -> str:
    """One `@final class <Name>Result:` block."""
    resolved = result_type(calc_id)
    hints = get_type_hints(resolved)
    out = ["@final", f"class {resolved.__name__}:"]
    for field in dataclasses.fields(resolved):
        out.append(f"    {field.name}: {stub_type(hints[field.name])}")
    if len(out) == 2:
        out.append("    ...")
    return "\n".join(out)


def parameter_record_fields(model: dict[str, Any]) -> list[str]:
    """The transport arguments a model's `params` record contributes, in field order.

    Which fields is a fact about the dataclass the parameter is *annotated* with, which
    is where this asks - the same move as reading the signature itself. The record
    carries the resolved parameters rather than the several loose vectors the transport
    wants, so this is also why the annotation has to be a dataclass in
    `azoth.eos.components`.

    The element type comes from the record too, so a field the transport carries as
    integers or as labels is not described as a list of floats. A field whose element
    type is not one of those is a float by the same convention the kernels use: a
    parameter set is numbers unless it says otherwise.
    """
    import importlib
    import inspect

    namespace, _, name = model["id"].partition(".")
    module = importlib.import_module(f"azoth.{namespace}")
    from azoth.eos import components as _components

    annotation = inspect.signature(getattr(module, name)).parameters["params"].annotation
    record = getattr(_components, annotation)
    hints = get_type_hints(record)
    fields: list[str] = []
    for field in dataclasses.fields(record):
        element = get_args(hints[field.name])
        kind = {int: "int", str: "str"}.get(element[0] if element else None, "float")
        fields.append(f"{field.name}: list[{kind}]")
    return fields


def transport_parameters(model: dict[str, Any]) -> list[str]:
    """The arguments a model's extension function takes, in the transport vocabulary.

    **Not the spec's declared inputs.** A calc's function takes the scalars its spec
    declares, so for a calc the two are the same. A model's takes *objects* - a
    `Mixture` and, where an enthalpy is involved, an `IdealGasModel` - and a `cdylib`
    has nothing to hold one in, so `_rust_bridge` flattens the mixture into four
    vectors and the ideal-gas model into five before it crosses. The stub describes
    the extension, so it has to describe that, not the spec.

    Which objects is a fact about the implementation's signature, so that is where
    this asks - the same question `python/tests/_helpers.py::parameters_of` asks, and
    for the same reason. A model that takes the critical constants themselves rather
    than a mixture (`eos.pure_saturation`) gets them as scalars, which is the same
    flattening with nothing to flatten.

    `components` is dropped: the resolved constants replace it, and a name list has
    no transport form of its own.
    """
    import importlib
    import inspect

    namespace, _, name = model["id"].partition(".")
    module = importlib.import_module(f"azoth.{namespace}")
    taken = set(inspect.signature(getattr(module, name)).parameters)

    params: list[str] = []
    # **One pass per fluid the model names**, so a model with two sides carries two
    # flattened mixtures. The prefix is the input's own - `components` gives the bare
    # names and `hot_components` gives `hot_` - which is what makes a second fluid an
    # input rather than a change to this function.
    for prefix, _ in fluid_inputs(model):
        if f"{prefix}mixture" in taken:
            params += [
                f"{prefix}Tc: list[float]",
                f"{prefix}Pc: list[float]",
                f"{prefix}omega: list[float]",
                f"{prefix}kij: list[float]",
            ]
            # The association, which the boundary used to drop: a mixture whose
            # association does not cross is a *different fluid* that converges, and
            # `eos.pt_flash` ran a classical SRK flash for a session because of it. It
            # is required rather than defaulted, so a caller that forgets gets a
            # `TypeError` instead of a plausible answer.
            params.append(f"{prefix}association: AssociationSpec")
            if model["id"] in MOLAR_MASS_MODELS:
                params.append(f"{prefix}molar_mass: list[float]")
            if model["id"] in LIQUID_VISCOSITY_MODELS:
                params.append(f"{prefix}liqvisc: list[float]")
                params.append(f"{prefix}liqvisc_model: list[int]")
            if "params" in taken:
                # A model that takes both a mixture and a parameter record - the
                # gamma-phi flash, whose vapour is a cubic and whose liquid is an
                # activity model - carries the record's own fields here, right after
                # the mixture's. The names are the record's, so whoever writes the
                # pyfunction reads them from the same place this does.
                params += parameter_record_fields(model)
        elif "coeffs" in taken:
            # A non-cubic reference EOS resolves the names into per-component coefficient
            # sets, flattened into the 32-coefficient `a` and the critical density.
            params += ["a: list[float]", "rhoc: list[float]"]
        elif "params" in taken:
            # An activity model resolves the names into a parameter set of its own
            # rather than a `Mixture`: critical constants are not what NRTL or UNIFAC
            # reads, so each set crosses as its own fields, flattened.
            #
            # Which fields is a fact about the dataclass the parameter is *annotated*
            # with, so that is where this asks - the same move as reading the signature
            # itself one line up, and the reason `params` carries a resolved record
            # rather than the several loose vectors the transport wants. The field order
            # is the transport order, and the kernel rebuilds by shape.
            params += parameter_record_fields(model)
        elif f"{prefix}components" in taken:
            # Either the EOS-CG mixture, which maps its own fixed component names, or a
            # process model, whose Rust side resolves the names itself. Both cross the
            # boundary verbatim rather than as a flattened mixture.
            params.append(f"{prefix}components: list[str]")
        else:
            params += [
                f"{prefix}Tc: float",
                f"{prefix}Pc: float",
                f"{prefix}omega: float",
            ]
        if f"{prefix}ideal_gas" in taken:
            params += [
                f"{prefix}{n}: list[float]" for n in ("cp_a", "cp_b", "cp_c", "cp_d", "cp_e")
            ]
    # **The declared inputs, optional ones last**, for the reason `ordered_parameters`
    # gives: the signature has to parse. **Every fluid is skipped**, because each is the
    # input the loop above resolved into a `Mixture` or its scalars, and a *second* one
    # the function does not take is one the boundary resolved beside it -
    # UNIFAC-UMR-PRU's parameter set, which a `params` record carries rather than a
    # signature. Asking the signature is what keeps the two rules from diverging:
    # `python/tests/_helpers.py` skips exactly these when it builds its own call.
    fluids = fluid_inputs(model)
    resolved = {name for _, name in fluids}
    resolved |= {f"{prefix}ideal_gas" for prefix, _ in fluids}
    for parameter, declaration in ordered_parameters(model["inputs"]):
        if parameter in resolved or parameter not in taken:
            continue
        params.append(render_parameter(parameter, declaration))
    if "hydrogen_type" in taken:
        # The hydrogen spin-isomer is a boundary-only choice carried as a string, not a
        # declared input: the spec names `T` and `P`, and the isomer is the caller's.
        params.append('hydrogen_type: str = "normal"')
    if "mixture" in taken:
        # The cubic and the alpha correlation the mixture is evaluated under, the two
        # boundary arguments the spec does not declare (they travel *inside* the
        # mixture, not beside it).
        params.append('eos: str = "pr"')
        # `alpha` is what NRTL calls its first matrix, so a model that carries both a
        # mixture and a parameter record spells this argument out rather than letting
        # the two collide.
        params.append('cubic_alpha: str = "pr"' if "params" in taken else 'alpha: str = "pr"')
        params.append("alpha_params: list[list[float]] | None = None")
    return params


def render_signature(entry: dict[str, Any]) -> str:
    """One `def <name>(...) -> <Name>Result: ...` block."""
    function = entry["id"].rpartition(".")[2]
    result_name = result_type(entry["id"]).__name__
    params = (
        transport_parameters(entry)
        if entry["id"] in MODEL_IDS
        else [render_parameter(name, d) for name, d in ordered_parameters(entry["inputs"])]
    )
    if not params:
        return f"def {function}() -> {result_name}: ..."
    # **Python has no syntax for a parameter with a default in front of one without**,
    # so a signature that has one does not parse - and a `.pyi` that does not parse
    # stops the type checker at that line rather than reporting it as a stub problem.
    # `process.separator` emitted exactly that: `heat_input` optional before a required
    # `gas_in_liquid`. The implementations put an optional input last for this reason,
    # and this refuses the alternative rather than emitting a file nothing can read.
    defaulted = [index for index, param in enumerate(params) if "=" in param]
    if defaulted and any("=" not in param for param in params[defaulted[0] :]):
        raise SystemExit(
            f"gen_stub: {entry['id']}: a parameter with a default is followed by one "
            f"without, which is not a valid Python signature. An optional input goes "
            f"last, in the spec and in every implementation."
        )
    single = f"def {function}({', '.join(params)}) -> {result_name}: ..."
    if len(single) <= 100:
        return single
    body = ",\n".join(f"    {param}" for param in params)
    return f"def {function}(\n{body},\n) -> {result_name}: ..."


def render_vocabulary() -> str:
    """The block of non-result types."""
    blocks = []
    for name, doc, fields in VOCABULARY:
        if name in TYPED_DICTS:
            # **An input record is a mapping and no class exists at runtime.** pyo3's
            # `FromPyObject` on a struct extracts one field per key; it does not export a
            # constructor, so a `@final class` here would describe something a caller
            # cannot build and would make a plain dict a type error at the call site.
            out = [f"class {name}(TypedDict):"]
            if doc:
                out.append(f'    """{doc}"""')
                out.append("")
            out.extend(f"    {field}: {annotation}" for field, annotation in fields)
            blocks.append("\n".join(out))
            continue
        out = ["@final", f"class {name}:"]
        if doc:
            out.append(f'    """{doc}"""')
            out.append("")
        out.extend(f"    {field}: {annotation}" for field, annotation in fields)
        if name == "Qty":
            out.append("    def __init__(self, magnitude_si: float, unit: str) -> None: ...")
        if name == "AssociationSpec":
            out.append(
                "    def __init__(self, associating: bool, schemes: list[str],"
                " values: list[list[float]]) -> None: ..."
            )
        if name == "Session":
            # **A handle, not a record.** Its state is a document and its methods are what a
            # caller does to one, so the stub declares the calls `azoth.process.Session`
            # makes and nothing else.
            out.extend(
                [
                    "    def __init__(self, document: str, palette_dir: str | None = ...)"
                    " -> None: ...",
                    "    def apply(self, command: str) -> str: ...",
                    "    def set_order(self, order: str) -> str: ...",
                    "    def run(self) -> str: ...",
                    "    def envelope(self) -> str: ...",
                    "    def document(self) -> str: ...",
                    "    def graph(self) -> str: ...",
                    "    def value(self, path: str) -> float: ...",
                    "    @property",
                    "    def paths(self) -> list[str]: ...",
                    "    @property",
                    "    def ok(self) -> bool: ...",
                    "    @property",
                    "    def dirty(self) -> bool: ...",
                    "    @property",
                    "    def run_error(self) -> str | None: ...",
                ]
            )
        if name == "Stream":
            out.append(
                "    def __init__(self, components: list[str], z: list[float], n: float,"
                " p: float, t: float) -> None: ..."
            )
            out.append("    @staticmethod")
            out.append(
                "    def from_ph(components: list[str], z: list[float], n: float, p: float,"
                " h: float) -> Stream: ..."
            )
        blocks.append("\n".join(out))
    # The rows a `record_list` input takes, one mapping type per `row_type`, generated from
    # the spec's `fields` rather than listed in `VOCABULARY` - see `record_rows`.
    for row, fields in record_rows().items():
        out = [
            f"class {row}(TypedDict):",
            '    """One row of a `record_list` input, as the extension takes it: the named '
            'fields the spec declares, each as the SI magnitude it crosses as."""',
            "",
        ]
        out.extend(
            f"    {field_name}: {record_field_type(declared)}"
            for field_name, declared in fields.items()
        )
        blocks.append("\n".join(out))
    # The rows a `record_list` output returns, one class per kernel struct. **Rendered from
    # the generated dataclass rather than from the spec**, because a quantity crosses back as
    # a `Qty` and `stub_type` is the one place that spelling lives; a second rule here would be
    # a second answer to the same question - see `record_output_rows`.
    import azoth.core.record_outputs_gen as record_outputs

    for row in record_output_rows():
        resolved = getattr(record_outputs, row)
        hints = get_type_hints(resolved)
        out = ["@final", f"class {row}:"]
        if resolved.__doc__:
            out.append(f'    """{resolved.__doc__}"""')
            out.append("")
        out.extend(
            f"    {field.name}: {stub_type(hints[field.name])}"
            for field in dataclasses.fields(resolved)
        )
        blocks.append("\n".join(out))
    return "\n\n".join(blocks)


def render() -> str:
    entries = sorted([*CALCS, *MODELS], key=lambda e: e["id"])
    classes = "\n\n".join(render_result_class(entry["id"]) for entry in entries)
    signatures = "\n".join(render_signature(entry) for entry in entries)
    introspection = "\n".join(
        f"def {signature} -> {result}: ..." for signature, result in INTROSPECTION
    )
    exceptions = "\n".join(f"class {name}({base}): ..." for name, base in EXCEPTIONS)

    return (
        f'"""{DOCSTRING}"""\n\n'
        "from typing import TypedDict, final\n\n"
        # **A result field can name an enum the stub does not define.** The transport
        # carries `selected_model` as a string, and the stub renders the *dataclass's*
        # annotation - which is `PlusModel`, declared in `azoth.core.result_base` beside
        # the phase and the stability verdict. Without the import the name is unresolved
        # and `mypy` refuses the whole file rather than the one field.
        "from azoth.core.result_base import PlusModel\n\n"
        "# --- transport types ------------------------------------------------------\n"
        "# The values that cross the boundary and are not results. Hand-written here\n"
        "# because a `cdylib` has nothing to introspect; held to the Rust structs by\n"
        "# `test_the_stub_matches_the_rust_transport_types`.\n\n"
        f"{render_vocabulary()}\n\n"
        "# --- results --------------------------------------------------------------\n"
        "# Generated from the result dataclasses, so the stub and `azoth.core.result`\n"
        "# cannot disagree about a field.\n\n"
        f"{classes}\n\n"
        "# --- calculations ---------------------------------------------------------\n"
        "# All arguments and returns are SI magnitudes; unit handling happens once, in\n"
        "# Python, before the call crosses this boundary. See crates/azoth-python.\n\n"
        f"{signatures}\n\n"
        "# --- introspection --------------------------------------------------------\n\n"
        f"{introspection}\n\n"
        "# --- exceptions -----------------------------------------------------------\n"
        "# Re-exported from azoth.core.errors, so both backends raise the same class\n"
        "# objects rather than two lookalike hierarchies.\n\n"
        f"{exceptions}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    args = parser.parse_args()

    content = render()
    if args.check:
        current = STUB.read_text(encoding="utf-8") if STUB.exists() else ""
        if current != content:
            sys.exit(f"gen_stub: {STUB} is out of date - run `python tools/gen_stub.py`")
        print(f"gen_stub: {STUB} is up to date")
        return 0

    STUB.write_text(content, encoding="utf-8")
    print(f"gen_stub: wrote {STUB}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
