#!/usr/bin/env python3
"""Generate the `#[derive(FromPyObject)]` rows a `record_list` input crosses in.

A record `record_list` input is a list of mappings, and pyo3 extracts one field per key - so the
Rust type it extracts into is a declaration of the row, and nothing about it is a decision:

* **the fields are the spec's `fields` block**, which is the same declaration `gen_stub` renders
  the stub's `TypedDict` from and `spec_lint` holds the shape of. `record_rows` is that reader, and
  this file imports it rather than walking `specs/` a second time: one reader of `fields`, two
  renderers, which is the arrangement `gen_python_result` and `gen_python_bridge` already have.
* **each field's Rust type is the magnitude it crosses as.** Python converts a dimensioned field
  before the boundary - `input_records_to_si`, the one conversion site - so a quantity arrives as
  a bare `f64` whatever unit the spec declares, and only the *name* of the field is left to carry
  the meaning.
* **an optional field is an `Option`**, which is what makes the per-entry absence the kind exists
  for a value rather than a key the extractor would refuse to miss.

Two things about the emitted shape are load-bearing rather than stylistic:

* **`#[pyo3(item)]` on every field and the derive on one line.** pyo3's default extraction is
  positional, and `test_the_record_row_is_one_shape_in_three_declarations` reads the source with
  `#\\[pyo3\\(item\\)\\]\\s*pub (\\w+):` - a struct of bare `pub` fields is found by the derive and
  reports **zero** fields, which fails as a mismatch rather than as a missing attribute.
* **no `#[pyclass]`.** An item struct is extracted without being registered, which is what keeps it
  out of `dir(azoth._core)` and out of the stub-versus-transport comparison that a registered type
  would join.

    python tools/gen_python_records.py            # write
    python tools/gen_python_records.py --check    # fail if the tree is not what this emits
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_stub import record_rows

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "azoth-python" / "src" / "records_gen.rs"

BANNER = (
    "//! GENERATED FILE - DO NOT EDIT BY HAND.\n"
    "//!\n"
    "//! Generated by `tools/gen_python_records.py` from each `record_list` input's own\n"
    "//! `fields` block, which `tools/gen_stub.py` renders the stub's mapping type from and\n"
    "//! `python/tests/test_registration_completeness.py` holds the kernel's row to.\n"
    "//!\n"
    "//! Regenerate with `python tools/gen_python_records.py`; CI runs `--check` and fails\n"
    "//! on any difference.\n"
)

#: How a field's declared kind crosses, beside the bare `f64` a quantity becomes.
KINDS = {"boolean": "bool", "enum": "String", "string": "String"}


def field_type(declared: dict[str, Any]) -> str:
    """The Rust type one record field extracts into.

    A dimensioned field has already been converted to its SI magnitude in Python, so it is an
    `f64` here whatever unit the spec declares - the same rule that makes the row shape a
    declaration of *names* rather than of units.
    """
    base = KINDS.get(declared.get("type", "quantity"), "f64")
    return f"Option<{base}>" if declared.get("optional", False) else base


def emit_struct(row: str, fields: dict[str, Any]) -> str:
    """One row's struct, in the order the spec declares its fields."""
    lines = [
        "/// One row of a `record_list` input, extracted from the mapping a caller passes.",
        "#[derive(Debug, Clone, Default, FromPyObject)]",
        f"pub struct {row} {{",
    ]
    lines.extend(
        f"    #[pyo3(item)]\n    pub {name}: {field_type(declared)},"
        for name, declared in fields.items()
    )
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    """The whole file, rows in name order so it is a stable diff."""
    rows = record_rows()
    body = "\n\n".join(emit_struct(row, fields) for row, fields in sorted(rows.items()))
    return BANNER + "\nuse pyo3::prelude::*;\n\n" + body + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the tree is out of date")
    args = parser.parse_args()

    content = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            sys.exit(
                "gen_python_records: crates/azoth-python/src/records_gen.rs is out of date - run "
                "`python tools/gen_python_records.py`"
            )
        print("gen_python_records: crates/azoth-python/src/records_gen.rs is current")
        return 0

    OUT.write_text(content, encoding="utf-8")
    print(f"gen_python_records: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
