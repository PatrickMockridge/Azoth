#!/usr/bin/env python3
"""Generate the `record_list` *output* rows: the pyclass, and the dataclass it is read as.

A record output is a list of kernel structs, so it needs a type on each side of the boundary, and
the two are one declaration:

* **the pyclass** (`crates/azoth-python/src/record_outputs_gen.rs`) is what the extension hands
  back - `frozen`, a `#[pyo3(get)]` per field, built only in Rust, so `skip_from_py_object` and no
  `#[new]`.
* **the dataclass** (`python/src/azoth/core/record_outputs_gen.py`) is what a caller reads, and
  what `tools/gen_python_bridge.py` rebuilds each row into, one `from_si` per dimensioned field.

The fields are the spec's own `[outputs.<key>.fields]` block, read through
`gen_stub.record_output_rows()` - the same reader the stub's class and the transport's import list
come from, because a second reading of `fields` would be a second place a row can change.

**This is the mirror of `tools/gen_python_records.py`, and the two cannot be one generator.** An
input row is built in Python and read in Rust (`FromPyObject`); an output row is built in Rust and
read in Python (`#[pyclass]`). They share the reader and nothing else.

    python tools/gen_python_record_outputs.py            # write
    python tools/gen_python_record_outputs.py --check    # fail if the tree is not what this emits
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_python_wrappers
import rust_index
from gen_python_transport import doc, element_kind, field_expr, field_type, parse_type
from gen_stub import record_output_rows

ROOT = Path(__file__).resolve().parent.parent
RUST_OUT = ROOT / "crates" / "azoth-python" / "src" / "record_outputs_gen.rs"
PYTHON_OUT = ROOT / "python" / "src" / "azoth" / "core" / "record_outputs_gen.py"

RUST_BANNER = (
    "//! GENERATED FILE - DO NOT EDIT BY HAND.\n"
    "//!\n"
    "//! Generated by `tools/gen_python_record_outputs.py` from each `record_list` output's own\n"
    "//! `fields` block, which `tools/gen_stub.py` renders the stub's class from and\n"
    "//! `python/tests/test_registration_completeness.py` holds the kernel struct to.\n"
    "//!\n"
    "//! Regenerate with `python tools/gen_python_record_outputs.py`; CI runs `--check` and\n"
    "//! fails on any difference.\n"
)

PYTHON_BANNER = (
    '"""The `record_list` output rows, emitted from the extension\'s own declarations.\n'
    "\n"
    "Generated by `tools/gen_python_record_outputs.py` from each output's `fields` block.\n"
    "**Do not edit by hand.** One frozen dataclass per row, `eq=False` for the same reason\n"
    "the results are: an equality would compare `pint` quantities.\n"
    '"""\n'
    "\n"
    "from __future__ import annotations\n"
    "\n"
    "from dataclasses import dataclass"
)

#: The element type each non-numeric kind is, on this side. The default is a quantity.
PY_LEAF = {"boolean": "bool", "string": "str", "enum": "str"}


def element_declaration(element: str) -> tuple[str, dict[str, Any]]:
    """The path the kernel element struct is reachable at, and its `pub` fields by name."""
    fields = gen_python_wrappers.record_fields(element)
    if fields is None:
        sys.exit(f"gen_python_record_outputs: no crate declares a `pub struct {element}`")
    for path in sorted(rust_index.CRATES.glob("*/src/**/*.rs")):
        text = rust_index._blank_comments(path.read_text(encoding="utf-8"))
        if re.search(rf"^pub struct {re.escape(element)}\s*\{{", text, re.M):
            return rust_index._item_path(path, element), dict(fields)
    sys.exit(f"gen_python_record_outputs: `{element}` has no `pub struct` body to name")


def rust_block(element: str, declaration: dict[str, Any]) -> tuple[str, bool]:
    """One row's pyclass, its `__repr__` and its `From` impl. `True` where it needs `PyQty`."""
    path, kernel = element_declaration(element)
    fields: list[tuple[str, str, str, str]] = []
    for name, declared in declaration["fields"].items():
        ty = kernel.get(name)
        if ty is None:
            sys.exit(
                f"gen_python_record_outputs: {element}.{name} is declared by the spec and no "
                f"such field is on the kernel struct; the two are one shape in two spellings"
            )
        optional, depth, inner = parse_type(ty)
        kind = element_kind(inner, declared.get("type", "scalar"))
        fields.append(
            (
                name,
                field_type(kind, depth, optional, declared.get("unit"), inner),
                doc(declared.get("description", name)),
                field_expr(name, kind, depth, optional, declared.get("unit"), inner, "row"),
            )
        )
    if len(fields) != len(kernel):
        sys.exit(
            f"gen_python_record_outputs: {element} declares {len(fields)} spec field(s) against "
            f"{len(kernel)} on the kernel struct; the two are one shape in two spellings"
        )

    lines = [
        f"/// {doc(declaration.get('description', element))}",
        "#[pyclass(",
        "    frozen,",
        "    skip_from_py_object,",
        '    module = "azoth._core",',
        f'    name = "{element}"',
        ")]",
        "#[derive(Debug, Clone, PartialEq)]",
        f"pub struct Py{element} {{",
    ]
    for name, ty, text, _ in fields:
        lines += [f"    /// {text}", "    #[pyo3(get)]", f"    pub {name}: {ty},"]
    lines += ["}", "", "#[pymethods]", f"impl Py{element} {{", "    fn __repr__(&self) -> String {"]
    parts = ", ".join(f"{name}={{}}" for name, *_ in fields)
    args = ", ".join(f"self.{name}" for name, *_ in fields)
    call = f'format!("{element}({parts})", {args})' if fields else f'"{element}()".to_string()'
    lines += [f"        {call}", "    }", "}", ""]
    lines += [
        f"impl From<&{path}> for Py{element} {{",
        f"    fn from(row: &{path}) -> Self {{",
        "        Self {",
    ]
    lines += [f"            {name}: {expr}," for name, _, _, expr in fields]
    lines += ["        }", "    }", "}"]
    return "\n".join(lines), any("PyQty" in ty for _, ty, _, _ in fields)


def python_block(element: str, declaration: dict[str, Any]) -> tuple[str, bool]:
    """One row's dataclass. `True` where it needs `Q`."""
    lines = ["", "", "@dataclass(frozen=True, slots=True, eq=False)", f"class {element}:"]
    lines.append(f'    """{doc(declaration.get("description", element))}"""')
    dimensioned = False
    for name, declared in declaration["fields"].items():
        text = doc(declared.get("description", name))
        leaf = PY_LEAF.get(declared.get("type", "quantity"))
        if leaf is None:
            leaf = "Q" if declared.get("unit") not in (None, "dimensionless") else "float"
            dimensioned = dimensioned or leaf == "Q"
        annotation = f"{leaf} | None" if declared.get("optional", False) else leaf
        lines += ["", f"    #: {text}", f"    {name}: {annotation}"]
    return "\n".join(lines), dimensioned


def render_rust() -> str:
    """The whole Rust file, rows in name order so it is a stable diff."""
    blocks = []
    needs_qty = False
    for element, declaration in sorted(record_output_rows().items()):
        block, qty = rust_block(element, declaration)
        needs_qty = needs_qty or qty
        blocks.append(block)
    imports = ["use pyo3::prelude::*;"]
    if needs_qty:
        imports.append("use crate::results::PyQty;")
    return RUST_BANNER + "\n" + "\n".join(imports) + "\n\n" + "\n\n".join(blocks) + "\n"


def render_python() -> str:
    """The whole Python file, rows in name order so it is a stable diff."""
    blocks = []
    needs_q = False
    for element, declaration in sorted(record_output_rows().items()):
        block, q = python_block(element, declaration)
        needs_q = needs_q or q
        blocks.append(block)
    imports = ""
    if needs_q:
        imports = "\n\nfrom azoth.core.units import Q"
    return PYTHON_BANNER + imports + "\n" + "\n".join(blocks) + "\n"


def format_rust(text: str) -> str:
    """Run the emitted Rust through rustfmt, which the committed file is compared against."""
    try:
        proc = subprocess.run(
            ["rustfmt", "--edition", "2024"],
            input=text,
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError:
        sys.exit(
            "gen_python_record_outputs: rustfmt is not on PATH, and the generated file is "
            "compared against rustfmt's own output - install the Rust toolchain"
        )
    if proc.returncode != 0:
        sys.exit(f"gen_python_record_outputs: rustfmt refused the output:\n{proc.stderr}")
    return proc.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the tree is out of date")
    args = parser.parse_args()

    for out, content in (
        (RUST_OUT, format_rust(render_rust())),
        (PYTHON_OUT, render_python()),
    ):
        if args.check:
            current = out.read_text(encoding="utf-8") if out.exists() else ""
            if current != content:
                sys.exit(
                    f"gen_python_record_outputs: {out.relative_to(ROOT)} is out of date - run "
                    "`python tools/gen_python_record_outputs.py`"
                )
            continue
        out.write_text(content, encoding="utf-8")
        print(f"gen_python_record_outputs: wrote {out.relative_to(ROOT)}")
    if args.check:
        print("gen_python_record_outputs: the generated record output rows are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
